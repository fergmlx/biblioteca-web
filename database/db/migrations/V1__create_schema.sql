-- Tablas principales. Flyway ejecuta esta migración.

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS citext;

SET ROLE biblioteca_owner;

CREATE SEQUENCE seq_numero_socio
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

CREATE TABLE rol (
    id_rol SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(30) NOT NULL,
    CONSTRAINT pk_rol PRIMARY KEY (id_rol),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre),
    CONSTRAINT ck_rol_nombre CHECK (nombre IN ('USUARIO', 'ADMINISTRADOR'))
);

CREATE TABLE pais (
    id_pais SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(80) NOT NULL,
    codigo_iso CHAR(2) NOT NULL,
    CONSTRAINT pk_pais PRIMARY KEY (id_pais),
    CONSTRAINT uq_pais_nombre UNIQUE (nombre),
    CONSTRAINT uq_pais_codigo_iso UNIQUE (codigo_iso),
    CONSTRAINT ck_pais_codigo_iso CHECK (codigo_iso = upper(codigo_iso))
);

CREATE TABLE genero (
    id_genero SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(80) NOT NULL,
    CONSTRAINT pk_genero PRIMARY KEY (id_genero),
    CONSTRAINT uq_genero_nombre UNIQUE (nombre)
);

CREATE TABLE condicion_ejemplar (
    id_condicion_ejemplar SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(40) NOT NULL,
    permite_prestamo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_condicion_ejemplar PRIMARY KEY (id_condicion_ejemplar),
    CONSTRAINT uq_condicion_ejemplar_nombre UNIQUE (nombre)
);

CREATE TABLE estado_prestamo (
    id_estado_prestamo SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(40) NOT NULL,
    CONSTRAINT pk_estado_prestamo PRIMARY KEY (id_estado_prestamo),
    CONSTRAINT uq_estado_prestamo_nombre UNIQUE (nombre),
    CONSTRAINT ck_estado_prestamo_nombre
        CHECK (nombre IN ('ACTIVO', 'DEVUELTO', 'CANCELADO', 'RENOVADO'))
);

CREATE TABLE tipo_participacion (
    id_tipo_participacion SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(40) NOT NULL,
    CONSTRAINT pk_tipo_participacion PRIMARY KEY (id_tipo_participacion),
    CONSTRAINT uq_tipo_participacion_nombre UNIQUE (nombre)
);

CREATE TABLE usuario (
    id_usuario UUID NOT NULL DEFAULT gen_random_uuid(),
    numero_socio VARCHAR(20),
    nombres VARCHAR(100) NOT NULL,
    apellido_paterno VARCHAR(60) NOT NULL,
    apellido_materno VARCHAR(60),
    correo CITEXT NOT NULL,
    contrasena_hash VARCHAR(255) NOT NULL,
    telefono VARCHAR(30),
    membresia_activa BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_rol SMALLINT NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_numero_socio UNIQUE (numero_socio),
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol)
        REFERENCES rol (id_rol) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_usuario_nombres CHECK (length(trim(nombres)) > 0),
    CONSTRAINT ck_usuario_apellido CHECK (length(trim(apellido_paterno)) > 0)
);

CREATE TABLE autor (
    id_autor UUID NOT NULL DEFAULT gen_random_uuid(),
    nombres VARCHAR(100) NOT NULL,
    apellido_paterno VARCHAR(60) NOT NULL,
    apellido_materno VARCHAR(60),
    id_pais SMALLINT,
    ruta_imagen VARCHAR(300),
    fecha_nacimiento DATE,
    fecha_fallecimiento DATE,
    biografia TEXT,
    CONSTRAINT pk_autor PRIMARY KEY (id_autor),
    CONSTRAINT fk_autor_pais FOREIGN KEY (id_pais)
        REFERENCES pais (id_pais) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT ck_autor_nombres CHECK (length(trim(nombres)) > 0),
    CONSTRAINT ck_autor_fechas CHECK (
        fecha_fallecimiento IS NULL OR fecha_nacimiento IS NULL
        OR fecha_fallecimiento >= fecha_nacimiento)
);

CREATE TABLE libro (
    id_libro UUID NOT NULL DEFAULT gen_random_uuid(),
    isbn VARCHAR(20),
    titulo VARCHAR(200) NOT NULL,
    editorial VARCHAR(150) NOT NULL,
    anio_publicacion SMALLINT NOT NULL,
    idioma VARCHAR(50) NOT NULL,
    sinopsis TEXT,
    ruta_portada VARCHAR(300),
    CONSTRAINT pk_libro PRIMARY KEY (id_libro),
    CONSTRAINT uq_libro_isbn UNIQUE (isbn),
    CONSTRAINT ck_libro_titulo CHECK (length(trim(titulo)) > 0),
    CONSTRAINT ck_libro_anio CHECK (anio_publicacion BETWEEN 1 AND 9999)
);

CREATE TABLE libro_autor (
    id_libro UUID NOT NULL,
    id_autor UUID NOT NULL,
    id_tipo_participacion SMALLINT NOT NULL,
    CONSTRAINT pk_libro_autor
        PRIMARY KEY (id_libro, id_autor, id_tipo_participacion),
    CONSTRAINT fk_libro_autor_libro FOREIGN KEY (id_libro)
        REFERENCES libro (id_libro) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_libro_autor_autor FOREIGN KEY (id_autor)
        REFERENCES autor (id_autor) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_libro_autor_tipo FOREIGN KEY (id_tipo_participacion)
        REFERENCES tipo_participacion (id_tipo_participacion)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE libro_genero (
    id_libro UUID NOT NULL,
    id_genero SMALLINT NOT NULL,
    CONSTRAINT pk_libro_genero PRIMARY KEY (id_libro, id_genero),
    CONSTRAINT fk_libro_genero_libro FOREIGN KEY (id_libro)
        REFERENCES libro (id_libro) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_libro_genero_genero FOREIGN KEY (id_genero)
        REFERENCES genero (id_genero) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE ejemplar (
    id_libro UUID NOT NULL,
    num_ejemplar SMALLINT NOT NULL,
    codigo_inventario VARCHAR(30),
    ubicacion VARCHAR(100),
    id_condicion_ejemplar SMALLINT NOT NULL,
    CONSTRAINT pk_ejemplar PRIMARY KEY (id_libro, num_ejemplar),
    CONSTRAINT uq_ejemplar_codigo_inventario UNIQUE (codigo_inventario),
    CONSTRAINT fk_ejemplar_libro FOREIGN KEY (id_libro)
        REFERENCES libro (id_libro) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_ejemplar_condicion FOREIGN KEY (id_condicion_ejemplar)
        REFERENCES condicion_ejemplar (id_condicion_ejemplar)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_ejemplar_numero CHECK (num_ejemplar > 0)
);

CREATE TABLE circulo_lectura (
    id_circulo UUID NOT NULL DEFAULT gen_random_uuid(),
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    tema VARCHAR(200),
    dia_semana VARCHAR(20) NOT NULL,
    hora TIME NOT NULL,
    cupo_maximo SMALLINT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    id_libro UUID,
    CONSTRAINT pk_circulo_lectura PRIMARY KEY (id_circulo),
    CONSTRAINT fk_circulo_libro FOREIGN KEY (id_libro)
        REFERENCES libro (id_libro) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT ck_circulo_nombre CHECK (length(trim(nombre)) > 0),
    CONSTRAINT ck_circulo_cupo CHECK (cupo_maximo > 0),
    CONSTRAINT ck_circulo_fechas CHECK (
        fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    CONSTRAINT ck_circulo_libro_o_tema CHECK (
        (id_libro IS NOT NULL AND NULLIF(trim(tema), '') IS NULL)
        OR
        (id_libro IS NULL AND NULLIF(trim(tema), '') IS NOT NULL))
);

CREATE TABLE solicitud_prestamo (
    id_solicitud UUID NOT NULL DEFAULT gen_random_uuid(),
    id_usuario UUID NOT NULL,
    id_libro UUID NOT NULL,
    fecha_solicitud TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_respuesta TIMESTAMPTZ,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    observaciones TEXT,
    CONSTRAINT pk_solicitud_prestamo PRIMARY KEY (id_solicitud),
    CONSTRAINT fk_solicitud_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_libro FOREIGN KEY (id_libro)
        REFERENCES libro (id_libro) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_solicitud_estado CHECK (
        estado IN ('PENDIENTE', 'ATENDIDA', 'RECHAZADA', 'CANCELADA')),
    CONSTRAINT ck_solicitud_fecha CHECK (
        fecha_respuesta IS NULL OR fecha_respuesta >= fecha_solicitud)
);

CREATE TABLE inscripcion_circulo (
    id_inscripcion UUID NOT NULL DEFAULT gen_random_uuid(),
    fecha_inscripcion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_baja TIMESTAMPTZ,
    id_usuario UUID NOT NULL,
    id_circulo UUID NOT NULL,
    es_excepcion_cupo BOOLEAN NOT NULL DEFAULT FALSE,
    motivo_excepcion TEXT,
    id_usuario_autoriza UUID,
    CONSTRAINT pk_inscripcion_circulo PRIMARY KEY (id_inscripcion),
    CONSTRAINT fk_inscripcion_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_inscripcion_circulo FOREIGN KEY (id_circulo)
        REFERENCES circulo_lectura (id_circulo)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_inscripcion_autorizador FOREIGN KEY (id_usuario_autoriza)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT ck_inscripcion_fechas CHECK (
        fecha_baja IS NULL OR fecha_baja >= fecha_inscripcion),
    CONSTRAINT ck_inscripcion_excepcion CHECK (
        (es_excepcion_cupo = FALSE AND motivo_excepcion IS NULL
         AND id_usuario_autoriza IS NULL)
        OR
        (es_excepcion_cupo = TRUE
         AND NULLIF(trim(motivo_excepcion), '') IS NOT NULL
         AND id_usuario_autoriza IS NOT NULL))
);

CREATE TABLE prestamo (
    id_prestamo UUID NOT NULL DEFAULT gen_random_uuid(),
    id_solicitud UUID,
    fecha_prestamo TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_limite TIMESTAMPTZ NOT NULL,
    fecha_devolucion TIMESTAMPTZ,
    id_estado_prestamo SMALLINT NOT NULL,
    id_usuario UUID NOT NULL,
    id_libro UUID NOT NULL,
    num_ejemplar SMALLINT NOT NULL,
    CONSTRAINT pk_prestamo PRIMARY KEY (id_prestamo),
    CONSTRAINT fk_prestamo_solicitud FOREIGN KEY (id_solicitud)
        REFERENCES solicitud_prestamo (id_solicitud)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_prestamo_estado FOREIGN KEY (id_estado_prestamo)
        REFERENCES estado_prestamo (id_estado_prestamo)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_prestamo_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_prestamo_ejemplar FOREIGN KEY (id_libro, num_ejemplar)
        REFERENCES ejemplar (id_libro, num_ejemplar)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_prestamo_limite CHECK (fecha_limite >= fecha_prestamo),
    CONSTRAINT ck_prestamo_devolucion CHECK (
        fecha_devolucion IS NULL OR fecha_devolucion >= fecha_prestamo)
);

CREATE TABLE favorito (
    id_usuario UUID NOT NULL,
    id_libro UUID NOT NULL,
    fecha_agregado TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_favorito PRIMARY KEY (id_usuario, id_libro),
    CONSTRAINT fk_favorito_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_favorito_libro FOREIGN KEY (id_libro)
        REFERENCES libro (id_libro) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE resena (
    id_usuario UUID NOT NULL,
    id_libro UUID NOT NULL,
    calificacion SMALLINT NOT NULL,
    comentario TEXT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_resena PRIMARY KEY (id_usuario, id_libro),
    CONSTRAINT fk_resena_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_resena_libro FOREIGN KEY (id_libro)
        REFERENCES libro (id_libro) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_resena_calificacion CHECK (calificacion BETWEEN 1 AND 5)
);

CREATE TABLE token_recuperacion (
    id_token UUID NOT NULL DEFAULT gen_random_uuid(),
    id_usuario UUID NOT NULL,
    token_hash VARCHAR(255) NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_expiracion TIMESTAMPTZ NOT NULL,
    fecha_uso TIMESTAMPTZ,
    CONSTRAINT pk_token_recuperacion PRIMARY KEY (id_token),
    CONSTRAINT fk_token_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT uq_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_token_fechas CHECK (fecha_expiracion > fecha_creacion),
    CONSTRAINT ck_token_uso CHECK (
        fecha_uso IS NULL OR fecha_uso >= fecha_creacion)
);

CREATE UNIQUE INDEX uq_solicitud_pendiente
    ON solicitud_prestamo (id_usuario, id_libro)
    WHERE estado = 'PENDIENTE';

CREATE UNIQUE INDEX uq_inscripcion_activa
    ON inscripcion_circulo (id_usuario, id_circulo)
    WHERE fecha_baja IS NULL;

CREATE UNIQUE INDEX uq_prestamo_activo_ejemplar
    ON prestamo (id_libro, num_ejemplar)
    WHERE fecha_devolucion IS NULL;

CREATE UNIQUE INDEX uq_token_vigente_usuario
    ON token_recuperacion (id_usuario)
    WHERE fecha_uso IS NULL;

CREATE INDEX idx_libro_titulo ON libro (titulo);
CREATE INDEX idx_autor_apellidos
    ON autor (apellido_paterno, apellido_materno, nombres);
CREATE INDEX idx_prestamo_usuario ON prestamo (id_usuario);
CREATE INDEX idx_prestamo_ejemplar ON prestamo (id_libro, num_ejemplar);
CREATE INDEX idx_solicitud_usuario ON solicitud_prestamo (id_usuario);
CREATE INDEX idx_solicitud_libro ON solicitud_prestamo (id_libro);
CREATE INDEX idx_inscripcion_usuario ON inscripcion_circulo (id_usuario);
CREATE INDEX idx_inscripcion_circulo ON inscripcion_circulo (id_circulo);

CREATE OR REPLACE FUNCTION fn_generar_numero_socio()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.numero_socio IS NULL OR trim(NEW.numero_socio) = '' THEN
        NEW.numero_socio := 'SO-' || lpad(nextval('seq_numero_socio')::text, 8, '0');
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_generar_numero_socio
BEFORE INSERT ON usuario
FOR EACH ROW EXECUTE FUNCTION fn_generar_numero_socio();

RESET ROLE;
